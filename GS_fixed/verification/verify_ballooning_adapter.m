%% verify_ballooning_adapter.m
% End-to-end validation of the P3 FEM -> legacy eq/eqfunc adapter on one
% interior flux surface.  The ballooning eigenvalue solver is deliberately
% not involved in this first coupling test.

clearvars;
close all;
clc;

thisDirectory = fileparts(mfilename('fullpath'));
gsRoot = fullfile(thisDirectory, '..');
projectRoot = fullfile(gsRoot, '..');

addpath(gsRoot, ...
    fullfile(projectRoot, 'equilibrium'));
setup_solve_GS;

%% Reference GEQDSK and test controls
gfile = fullfile(projectRoot, 'gfiles', 'geqdsk_PT0.6');
targetPsiN = 0.7;
nSurfacePoint = 512;

reference = read_geqdsk(gfile);
referenceFunction = build_interpolants(reference);
boundary = clean_boundary(reference.rbbbs, reference.zbbbs);

referenceSpan = reference.sibry-reference.simag;
if ~isfinite(referenceSpan) || referenceSpan == 0
    error('VERIFY_ADAPTER:FluxSpan', ...
        'The reference GEQDSK flux span must be finite and nonzero.');
end

%% Re-solve the reference equilibrium with the P3 fixed-boundary solver
input = struct();

input.grid = struct( ...
    'nBoundary', size(boundary, 1), ...
    'NR', 72, ...
    'NZ', 72, ...
    'quadratureDegree', 10, ...
    'nProfile', reference.nw);

input.dim = struct( ...
    'R0', reference.rcentr, ...
    'B0', reference.fpol(end)/reference.rcentr, ...
    'aMinor', 0.5*range(boundary(:, 1)));

input.profile = struct( ...
    'mode', 1, ...
    'pprime', reference.pprime(:)*referenceSpan, ...
    'FFprime', reference.ffprim(:)*referenceSpan, ...
    'pedge', reference.pres(end));

input.boundary = struct( ...
    'R', boundary(:, 1), ...
    'Z', boundary(:, 2), ...
    'psiBoundary', 0);

input.Picard = struct( ...
    'omega', 0.5, ...
    'maxIterations', 150, ...
    'updateTolerance', 1.e-8, ...
    'residualTolerance', 1.e-8, ...
    'axisMode', 'max', ...
    'symmetryTolerance', 1.e-12, ...
    'fluxSpanTolerance', 1.e-12);

input.qEvaluation = struct( ...
    'interiorPsiN', unique([ ...
        0.05:0.05:0.80, 0.825:0.025:0.95]).', ...
    'contourNR', 241);

input.output = struct( ...
    'verbose', false, ...
    'checkTime', false, ...
    'showPlot', false);

equilibrium = solve_GS(input);

%% Build the adapter and extract one flux surface through the legacy API
[femEq, femFunction, adapterDiagnostics] = ...
    build_ballooning_adapter(equilibrium, NR=257);

femSurface = extract_flux_surface( ...
    femEq, femFunction, targetPsiN, Npoints=nSurfacePoint);

femIntegral = compute_contour_integrals( ...
    femEq, femFunction, femSurface, isNormalized=false);

referenceSurface = extract_flux_surface( ...
    reference, referenceFunction, targetPsiN, ...
    Npoints=nSurfacePoint);

referenceIntegral = compute_contour_integrals( ...
    reference, referenceFunction, referenceSurface, ...
    isNormalized=false);

%% Adapter consistency checks
surfaceValue = femFunction.eval(femSurface.R, femSurface.Z);
surfacePsiNRms = sqrt(mean((surfaceValue.psiN-targetPsiN).^2));
surfacePsiNMaximum = max(abs(surfaceValue.psiN-targetPsiN));

qRelativeError = abs(femIntegral.q_int-femIntegral.q_geqdsk) ...
    /max(abs(femIntegral.q_geqdsk), eps);

surfaceDistance = hypot( ...
    femSurface.R-referenceSurface.R, ...
    femSurface.Z-referenceSurface.Z);
surfaceRmsDistance = sqrt(mean(surfaceDistance.^2));
surfaceNormalizedRmsDistance = ...
    surfaceRmsDistance/input.dim.aMinor;

volumeRelativeError = abs(femIntegral.V-referenceIntegral.V) ...
    /max(abs(referenceIntegral.V), eps);
VprimeRelativeError = abs(femIntegral.Vprime-referenceIntegral.Vprime) ...
    /max(abs(referenceIntegral.Vprime), eps);

adapterSpan = femEq.sibry-femEq.simag;
expectedPprimeGrid = interp1( ...
    equilibrium.profile.psiN, ...
    equilibrium.profile.dp_dpsiN, ...
    femEq.psin(:), 'pchip')/adapterSpan;

expectedFFprimeGrid = interp1( ...
    equilibrium.profile.psiN, ...
    equilibrium.profile.FdF_dpsiN, ...
    femEq.psin(:), 'pchip')/adapterSpan;

profileGridConversionError = max([ ...
    norm(femEq.pprime(:)-expectedPprimeGrid, inf), ...
    norm(femEq.ffprim(:)-expectedFFprimeGrid, inf)]);

expectedPprime = interp1( ...
    femEq.psin(:), femEq.pprime(:), targetPsiN, 'linear');

expectedFFprime = interp1( ...
    femEq.psin(:), femEq.ffprim(:), targetPsiN, 'linear');

pprimeRelativeError = abs( ...
    femFunction.pprime(targetPsiN)-expectedPprime) ...
    /max(abs(expectedPprime), 1);

FFprimeRelativeError = abs( ...
    femFunction.FFprime(targetPsiN)-expectedFFprime) ...
    /max(abs(expectedFFprime), 1);

fprintf('\nP3 FEM ballooning adapter diagnostics.\n');
fprintf('  target psiN                     = %.4f\n', targetPsiN);
fprintf('  surface psiN RMS / max          = %.3e / %.3e\n', ...
    surfacePsiNRms, surfacePsiNMaximum);
fprintf('  q integral/profile relative     = %.3e\n', qRelativeError);
fprintf('  FEM/reference surface RMS / a   = %.3e\n', ...
    surfaceNormalizedRmsDistance);
fprintf('  FEM/reference V relative        = %.3e\n', ...
    volumeRelativeError);
fprintf('  FEM/reference Vprime relative   = %.3e\n', ...
    VprimeRelativeError);
fprintf('  pprime conversion relative      = %.3e\n', ...
    pprimeRelativeError);
fprintf('  FFprime conversion relative     = %.3e\n', ...
    FFprimeRelativeError);
fprintf('  profile-grid conversion absolute = %.3e\n', ...
    profileGridConversionError);
fprintf('  finite Cartesian-cache fraction = %.3f\n', ...
    adapterDiagnostics.finiteGridFraction);

assert(equilibrium.solverResult.converged, ...
    'VERIFY_ADAPTER:GSConvergence', ...
    'The P3 Grad-Shafranov solve did not converge.');

assert(femEq.simag == 0 && femEq.sibry > 0, ...
    'VERIFY_ADAPTER:FluxConvention', ...
    'The adapter flux coordinate is not outward-increasing.');

assert(surfacePsiNRms < 2.e-3 && surfacePsiNMaximum < 1.e-2, ...
    'VERIFY_ADAPTER:SurfaceFlux', ...
    'The extracted FEM surface is not sufficiently close to target psiN.');

assert(qRelativeError < 1.e-2, ...
    'VERIFY_ADAPTER:QIntegral', ...
    'The adapter contour-integral q does not match its q profile.');

assert(isfinite(femIntegral.V) && femIntegral.V > 0 && ...
       isfinite(femIntegral.Vprime) && femIntegral.Vprime > 0, ...
    'VERIFY_ADAPTER:Volume', ...
    'The adapter produced an invalid V or Vprime.');

assert(surfaceNormalizedRmsDistance < 3.e-2, ...
    'VERIFY_ADAPTER:ReferenceSurface', ...
    'The FEM and reference GEQDSK surfaces differ excessively.');

assert(volumeRelativeError < 3.e-2 && VprimeRelativeError < 8.e-2, ...
    'VERIFY_ADAPTER:ReferenceIntegral', ...
    'The FEM and reference contour integrals differ excessively.');

assert(pprimeRelativeError < 1.e-12 && ...
       FFprimeRelativeError < 1.e-12 && ...
       profileGridConversionError < 1.e-12, ...
    'VERIFY_ADAPTER:ProfileDerivative', ...
    'The normalized-to-dimensional profile conversion is inconsistent.');

assert(~adapterDiagnostics.usedReferenceFallback, ...
    'VERIFY_ADAPTER:ReferenceMetadata', ...
    'The finalized equilibrium did not preserve its reference metadata.');

fprintf('\nP3 FEM ballooning adapter verification passed.\n');


function boundary = clean_boundary(R, Z)
    boundary = [R(:), Z(:)];

    if size(boundary, 1) < 3 || any(~isfinite(boundary), 'all')
        error('VERIFY_ADAPTER:Boundary', ...
            'The GEQDSK boundary is invalid.');
    end

    scale = max([range(boundary(:, 1)), range(boundary(:, 2)), 1]);
    tolerance = 1.e-12*scale;

    keep = [true; hypot(diff(boundary(:, 1)), ...
        diff(boundary(:, 2))) > tolerance];
    boundary = boundary(keep, :);

    if norm(boundary(end, :)-boundary(1, :)) <= tolerance
        boundary(end, :) = [];
    end

    if size(boundary, 1) < 3
        error('VERIFY_ADAPTER:Boundary', ...
            'The GEQDSK boundary has too few unique points.');
    end
end

function marginal = first_marginal_alpha(alpha, lambdaMap)
    marginal = nan(size(lambdaMap, 1), 1);

    for row = 1:size(lambdaMap, 1)
        value = lambdaMap(row, :);
        crossing = find( ...
            value(1:end-1) <= 0 & value(2:end) >= 0, 1, 'first');

        if isempty(crossing)
            continue;
        end

        lambdaLeft = value(crossing);
        lambdaRight = value(crossing+1);
        alphaLeft = alpha(crossing);
        alphaRight = alpha(crossing+1);

        if lambdaRight == lambdaLeft
            marginal(row) = 0.5*(alphaLeft+alphaRight);
        else
            marginal(row) = alphaLeft-lambdaLeft ...
                *(alphaRight-alphaLeft)/(lambdaRight-lambdaLeft);
        end
    end
end

%% verify_fem_direct_salpha_scan.m
% Generate a converged s-alpha diagram from a strongly indented P3 FEM
% equilibrium after the circular, PT, and NT reference benchmarks pass.

%% Reuse the arbitrary-shape equilibrium and point verification
run(fullfile(fileparts(mfilename('fullpath')), ...
    'verify_indented_direct_ballooning_point.m'));

%% Coarse scan through the one-call FEM entry point
coarseShatGrid = linspace(0, 5, 9);
coarseAlphaGrid = linspace(0, 8, 11);
coarseNTheta0 = 8;
coarseTheta0Grid = 2*pi*((0:coarseNTheta0-1) ...
    - floor(coarseNTheta0/2))/coarseNTheta0;

[coarseScan, scanState] = scan_fem_salpha_diagram( ...
    equilibrium, targetPsiN, ...
    AdapterNR=257, ...
    NSurfacePoints=512, ...
    FourierModes=48, ...
    ProjectionIterations=2, ...
    EnforceDirectQ=true, ...
    Shat=coarseShatGrid, ...
    Alpha=coarseAlphaGrid, ...
    Theta0=coarseTheta0Grid, ...
    ThetaBoundary=5*pi, ...
    NBalloonPoints=121, ...
    EnforcePeriodicity=true, ...
    Verbose=true);

%% Refined production diagram
fineShatGrid = linspace(0, 5, 17);
fineAlphaGrid = linspace(0, 8, 25);
fineNTheta0 = 12;
fineTheta0Grid = 2*pi*((0:fineNTheta0-1) ...
    - floor(fineNTheta0/2))/fineNTheta0;

fineScan = scan_salpha_diagram( ...
    scanState, ...
    Shat=fineShatGrid, ...
    Alpha=fineAlphaGrid, ...
    Theta0=fineTheta0Grid, ...
    ThetaBoundary=5*pi, ...
    NBalloonPoints=121, ...
    EnforcePeriodicity=true, ...
    Verbose=true);

%% Independently converged marginal boundary
marginalNTheta0 = 16;
marginalTheta0Grid = 2*pi*((0:marginalNTheta0-1) ...
    - floor(marginalNTheta0/2))/marginalNTheta0;

marginalTrace = trace_salpha_marginal( ...
    scanState, ...
    fineShatGrid, ...
    AlphaBracket=[0, 3], ...
    AlphaTolerance=5.e-3, ...
    MaxIterations=12, ...
    Theta0=marginalTheta0Grid, ...
    ThetaBoundary=5*pi, ...
    NBalloonPoints=121, ...
    EnforcePeriodicity=true, ...
    Verbose=true);

coarseMarginal = first_marginal_alpha( ...
    coarseScan.alpha, coarseScan.lambdaMax);
fineMarginal = first_marginal_alpha( ...
    fineScan.alpha, fineScan.lambdaMax);
fineMarginalOnCoarseShat = fineMarginal(1:2:end);
sharedMarginal = isfinite(coarseMarginal) ...
    & isfinite(fineMarginalOnCoarseShat);
marginalDifference = fineMarginalOnCoarseShat(sharedMarginal) ...
    - coarseMarginal(sharedMarginal);
marginalRmsDifference = sqrt(mean(marginalDifference.^2));
marginalMaximumDifference = max(abs(marginalDifference));

adaptiveMarginal = marginalTrace.marginalAlpha(:);
sharedAdaptiveMarginal = isfinite(fineMarginal) ...
    & isfinite(adaptiveMarginal);
adaptiveDifference = adaptiveMarginal(sharedAdaptiveMarginal) ...
    - fineMarginal(sharedAdaptiveMarginal);
adaptiveRmsDifference = sqrt(mean(adaptiveDifference.^2));
adaptiveMaximumDifference = max(abs(adaptiveDifference));

fprintf('\nIndented FEM direct s-alpha scan diagnostics.\n');
fprintf('  coarse size (shat,alpha,theta0) = %d x %d x %d\n', ...
    numel(coarseScan.shat), numel(coarseScan.alpha), ...
    numel(coarseScan.theta0));
fprintf('  fine size (shat, alpha, theta0) = %d x %d x %d\n', ...
    numel(fineScan.shat), numel(fineScan.alpha), ...
    numel(fineScan.theta0));
fprintf('  lambda range                    = [%+.8e, %+.8e]\n', ...
    fineScan.lambdaRange(1), fineScan.lambdaRange(2));
fprintf('  failed eigenvalue solves        = %d\n', ...
    fineScan.numberFailed);
fprintf('  marginal crossing found         = %d\n', ...
    fineScan.hasMarginalCrossing);
fprintf('  coarse/fine marginal RMS / max  = %.3e / %.3e\n', ...
    marginalRmsDifference, marginalMaximumDifference);
fprintf('  fine/adaptive marginal RMS/max  = %.3e / %.3e\n', ...
    adaptiveRmsDifference, adaptiveMaximumDifference);
fprintf('  adaptive bracket maximum width  = %.3e\n', ...
    max(marginalTrace.bracketWidth));
fprintf('  maximum periodic closure        = %.3e\n', ...
    max(abs(fineScan.periodicityClosure), [], 'all'));

assert(coarseScan.numberFailed == 0 && ...
       fineScan.numberFailed == 0 && ...
       marginalTrace.numberFailed == 0, ...
    'VERIFY_FEM_SALPHA:FailedSolve', ...
    'At least one FEM direct s-alpha eigenvalue solve failed.');

assert(all(isfinite(coarseScan.lambdaMax), 'all') && ...
       all(isfinite(fineScan.lambdaMax), 'all'), ...
    'VERIFY_FEM_SALPHA:NonfiniteMap', ...
    'The FEM direct s-alpha map contains non-finite eigenvalues.');

assert(all(coarseScan.lambdaMax(:, 1) < 0) && ...
       all(fineScan.lambdaMax(:, 1) < 0), ...
    'VERIFY_FEM_SALPHA:ZeroAlpha', ...
    'The alpha=0 column must remain stable on the finite domain.');

assert(coarseScan.hasMarginalCrossing && ...
       fineScan.hasMarginalCrossing, ...
    'VERIFY_FEM_SALPHA:NoMarginalBoundary', ...
    'The selected scan range did not capture a lambda=0 boundary.');

assert(max(abs(fineScan.periodicityClosure), [], 'all') < 1.e-10, ...
    'VERIFY_FEM_SALPHA:Periodicity', ...
    'The s-alpha scan did not preserve theta_psi periodicity.');

assert(strcmp(scanState.localEquilibrium.model, ...
        'direct-flux-surface'), ...
    'VERIFY_FEM_SALPHA:WrongModel', ...
    'The FEM scan entry point did not select direct surface geometry.');

assert(nnz(sharedMarginal) >= 0.75*numel(coarseShatGrid), ...
    'VERIFY_FEM_SALPHA:CoarseMarginalCoverage', ...
    'Too few coarse/fine rows contain a shared marginal crossing.');

assert(marginalTrace.numberConverged == numel(fineShatGrid) && ...
       marginalTrace.numberUnbracketed == 0 && ...
       max(marginalTrace.bracketWidth) <= 5.e-3, ...
    'VERIFY_FEM_SALPHA:MarginalConvergence', ...
    'The C-shape marginal boundary is not converged in scan resolution.');

%% Render a reproducible diagram artifact
figures = plot_salpha_diagram( ...
    fineScan, ...
    Visible="on", ...
    ShowPhase=true, ...
    Title="Indented FEM direct flux-surface $s$-$\alpha$");

hold(figures.stabilityAxes, 'on');
plot(figures.stabilityAxes, ...
    marginalTrace.marginalAlpha, marginalTrace.shat, ...
    'w--', 'LineWidth', 2.0);


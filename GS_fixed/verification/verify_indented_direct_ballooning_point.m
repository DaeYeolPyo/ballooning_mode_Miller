%% verify_indented_direct_ballooning_point.m
% Exercise the direct FEM-to-ballooning path on a strongly indented shape.
% This case has no GEQDSK or Miller reference: the checks are geometric
% closure, internal coefficient identities, and Fourier-mode convergence.

clearvars;
close all;
clc;

%% Repository setup
thisDirectory = fileparts(mfilename('fullpath'));
gsRoot = fullfile(thisDirectory, '..');
projectRoot = fullfile(gsRoot, '..');

addpath(gsRoot, ...
    fullfile(projectRoot, 'equilibrium'), ...
    fullfile(projectRoot, 'local_equilibrium'), ...
    fullfile(projectRoot, 'ballooning_equation'), ...
    fullfile(projectRoot, 'sturm_liouville_solver'), ...
    fullfile(projectRoot, 'salpha'));
setup_solve_GS;

%% Strongly indented fixed-boundary equilibrium
R0 = 3.0;
aMinor = 1.0;
kappa = 5.0;
delta = -0.4;
indent = 0.8;
B0 = 2.0;

nBoundary = 100;
nProfile = 101;

thetaBoundary = (0:nBoundary-1).'*(2*pi/nBoundary);
triangularityAngle = asin(delta);

RBoundary = R0 + aMinor*cos( ...
    thetaBoundary+triangularityAngle*sin(thetaBoundary)) ...
    - indent*aMinor*(0.5+0.5*cos(thetaBoundary)).^3;
ZBoundary = kappa*aMinor*sin(thetaBoundary);

psiNProfile = linspace(0, 1, nProfile).';
pprime = -1.0e6*(1-psiNProfile.^1.5).^2;
FFprime = 0.6*(1-psiNProfile.^2);

input = struct();
input.grid = struct( ...
    'nBoundary', nBoundary, ...
    'NR', 48, ...
    'NZ', 64, ...
    'quadratureDegree', 7, ...
    'nProfile', nProfile);

input.dim = struct( ...
    'R0', R0, 'B0', B0, 'aMinor', aMinor);

input.boundary = struct( ...
    'R', RBoundary, ...
    'Z', ZBoundary, ...
    'psiBoundary', 0.0);

input.Picard = struct( ...
    'omega', 0.5, ...
    'maxIterations', 250, ...
    'updateTolerance', 2.0e-7, ...
    'residualTolerance', 5.0e-7, ...
    'axisMode', 'max', ...
    'symmetryTolerance', 1.0e-12, ...
    'fluxSpanTolerance', 1.0e-12);

input.profile = struct( ...
    'mode', 1, ...
    'pprime', pprime, ...
    'FFprime', FFprime, ...
    'pedge', 0.0);

input.qEvaluation = struct( ...
    'interiorPsiN', [0.05:0.05:0.85, 0.90, 0.95].', ...
    'contourNR', 160);

input.output = struct( ...
    'verbose', false, ...
    'checkTime', false, ...
    'showPlot', false);

equilibrium = solve_GS(input);

%% Direct local geometry at two Fourier resolutions
targetPsiN = 0.7;
nSurfacePoint = 512;

[eq, eqfunc, adapterDiagnostics] = ...
    build_ballooning_adapter(equilibrium, NR=257);

state32 = prepare_salpha_equilibrium( ...
    eq, eqfunc, targetPsiN, ...
    Model="Direct", ...
    NSurfacePoints=nSurfacePoint, ...
    FourierModes=32, ...
    ProjectionIterations=2, ...
    EnforceDirectQ=true, ...
    EnforcePeriodicity=true);

state48 = prepare_salpha_equilibrium( ...
    eq, eqfunc, targetPsiN, ...
    Model="Direct", ...
    NSurfacePoints=nSurfacePoint, ...
    FourierModes=48, ...
    ProjectionIterations=2, ...
    EnforceDirectQ=true, ...
    EnforcePeriodicity=true);

theta0 = 0;
ballooningBoundary = 5*pi;
thetaGrid = linspace(-ballooningBoundary, ballooningBoundary, 151).';

point32 = solve_ballooning_point( ...
    state32, theta0, ballooningBoundary, thetaGrid);
point48 = solve_ballooning_point( ...
    state48, theta0, ballooningBoundary, thetaGrid);

%% Resolution-convergence and consistency diagnostics
geometry32 = state32.localEquilibrium;
geometry48 = state48.localEquilibrium;
diagnostic48 = state48.diagnostics.directGeometry;

BpModeDifference = relative_l2(geometry32.Bp, geometry48.Bp);
curvatureModeDifference = relative_l2( ...
    geometry32.invRc, geometry48.invRc);

gModeDifference = relative_l2(point32.g, point48.g);
cModeDifference = relative_l2(point32.c, point48.c);
fModeDifference = relative_l2(point32.f, point48.f);

lambdaScale = max([abs(point32.lambda), abs(point48.lambda), 1.e-3]);
lambdaModeDifference = abs(point32.lambda-point48.lambda)/lambdaScale;

coefficientValidation = point48.coefficient.validation;
coefficientIdentityError = max([ ...
    coefficientValidation.K_relative_error, ...
    coefficientValidation.D_relative_error, ...
    coefficientValidation.g_relative_error, ...
    coefficientValidation.c_relative_error, ...
    coefficientValidation.f_relative_error]);

fprintf('\nIndented direct FEM ballooning diagnostics.\n');
fprintf('  shape (kappa, delta, indent)       = %.1f, %.1f, %.1f\n', ...
    kappa, delta, indent);
fprintf('  GS iterations / residual          = %d / %.3e\n', ...
    equilibrium.solverResult.iterations, ...
    equilibrium.solverResult.finalRelativeResidual);
fprintf('  target psiN / q                   = %.3f / %.8f\n', ...
    targetPsiN, state48.surface.q);
fprintf('  shat / alpha                      = %+.8e / %+.8e\n', ...
    state48.shat, state48.alpha);
fprintf('  surface psiN RMS / max            = %.3e / %.3e\n', ...
    diagnostic48.psiNRms, diagnostic48.psiNMaximum);
fprintf('  minimum normal alignment          = %.8f\n', ...
    diagnostic48.minimumNormalAlignment);
fprintf('  q correction / q relative error   = %.8f / %.3e\n', ...
    diagnostic48.qCorrection, diagnostic48.qRelativeError);
fprintf('  PEST / theta_psi closure          = %.3e / %.3e\n', ...
    diagnostic48.PESTClosure, state48.thetaDiag.closure_used);
fprintf('  32/48 Bp / curvature relative L2  = %.3e / %.3e\n', ...
    BpModeDifference, curvatureModeDifference);
fprintf('  32/48 g / c / f relative L2       = %.3e / %.3e / %.3e\n', ...
    gModeDifference, cModeDifference, fModeDifference);
fprintf('  32/48 largest lambda              = %+.8e / %+.8e\n', ...
    point32.lambda, point48.lambda);
fprintf('  32/48 lambda relative difference  = %.3e\n', ...
    lambdaModeDifference);
fprintf('  coefficient identity max error    = %.3e\n', ...
    coefficientIdentityError);
fprintf('  finite Cartesian-cache fraction   = %.3f\n', ...
    adapterDiagnostics.finiteGridFraction);

%% Acceptance checks
assert(equilibrium.solverResult.converged, ...
    'VERIFY_INDENTED_DIRECT:GSConvergence', ...
    'The strongly indented P3 Grad-Shafranov solve did not converge.');

assert(diagnostic48.psiNRms < 2.e-3 && ...
       diagnostic48.psiNMaximum < 1.e-2, ...
    'VERIFY_INDENTED_DIRECT:SurfaceFlux', ...
    'The direct geometry drifted away from the target flux surface.');

assert(diagnostic48.minimumNormalAlignment > 0.95, ...
    'VERIFY_INDENTED_DIRECT:NormalAlignment', ...
    'The geometric normal is not aligned with grad(psi).');

assert(abs(diagnostic48.qRelativeError) < 1.e-10 && ...
       abs(diagnostic48.PESTClosure) < 1.e-10 && ...
       abs(state48.thetaDiag.closure_used) < 1.e-10, ...
    'VERIFY_INDENTED_DIRECT:Periodicity', ...
    'The q, PEST, or theta_psi periodic closure is inconsistent.');

assert(BpModeDifference < 2.e-2 && ...
       curvatureModeDifference < 8.e-2, ...
    'VERIFY_INDENTED_DIRECT:GeometryConvergence', ...
    'The direct geometry is not converged in Fourier resolution.');

assert(gModeDifference < 5.e-2 && ...
       cModeDifference < 5.e-2 && ...
       fModeDifference < 5.e-2, ...
    'VERIFY_INDENTED_DIRECT:CoefficientConvergence', ...
    'The ballooning coefficients are not converged in Fourier resolution.');

assert(lambdaModeDifference < 5.e-2, ...
    'VERIFY_INDENTED_DIRECT:EigenvalueConvergence', ...
    'The ballooning eigenvalue is not converged in Fourier resolution.');

assert(coefficientValidation.all_finite && ...
       all(point48.g > 0) && all(point48.f > 0) && ...
       coefficientIdentityError < 1.e-10 && ...
       isfinite(point48.lambda), ...
    'VERIFY_INDENTED_DIRECT:BallooningSystem', ...
    'The assembled ballooning system failed its internal checks.');

fprintf('\nStrongly indented direct FEM ballooning verification passed.\n');


function point = solve_ballooning_point( ...
    state, theta0, thetaBoundary, thetaGrid)

    coefficient = evaluate_gcf( ...
        state.thetaDiag, theta0, ...
        theta_bnd=thetaBoundary, ...
        a_N=state.normalization.aN, ...
        B_N=state.normalization.BN);

    g = interp1( ...
        coefficient.theta, coefficient.g, thetaGrid, 'pchip');
    c = interp1( ...
        coefficient.theta, coefficient.c, thetaGrid, 'pchip');
    f = interp1( ...
        coefficient.theta, coefficient.f, thetaGrid, 'pchip');

    [Gmatrix, Cmatrix, Fmatrix, thetaDof] = ...
        construct_matrix(thetaGrid, g, c, f);

    lambda = calculate_eigenvalue( ...
        thetaDof, Gmatrix, Cmatrix, Fmatrix, 'dirichlet');

    point = struct();
    point.coefficient = coefficient;
    point.g = g;
    point.c = c;
    point.f = f;
    point.lambda = lambda(1);
end


function error = relative_l2(actual, reference)
    error = norm(actual(:)-reference(:)) ...
        /max(norm(reference(:)), eps);
end

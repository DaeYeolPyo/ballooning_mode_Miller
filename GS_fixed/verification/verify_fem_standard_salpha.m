%% verify_fem_standard_salpha.m
% Validate the FEM direct-flux-surface s-alpha path in increasing order of
% geometric complexity: circular, positive triangularity, then negative
% triangularity.  C-shapes are deliberately excluded from this benchmark.
%
% Reference paths
%   circular : GEQDSK + analytic Circular_Mercier_Luc
%   PT / NT  : GEQDSK + existing Miller_Mercier_Luc
%
% Each reference is compared with both GEQDSK-Direct and FEM-Direct on the
% same (shat,alpha,theta0) grid.

clearvars;
close all;
clc;

%% Repository setup
thisDirectory = fileparts(mfilename('fullpath'));
gsRoot = fullfile(thisDirectory, '..');
projectRoot = fullfile(gsRoot, '..');

addpath(gsRoot, ...
    fullfile(projectRoot, 'equilibrium'), ...
    fullfile(projectRoot, 'local_equilibrium'), ...
    fullfile(projectRoot, 'ballooning_equation'), ...
    fullfile(projectRoot, 'sturm_liouville_solver'), ...
    fullfile(projectRoot, 'salpha'));
setup_solve_GS;

%% Common scan resolution
nSurfacePoint = 512;
nBalloonPoint = 121;
nTheta0 = 8;
theta0Grid = 2*pi*((0:nTheta0-1)-floor(nTheta0/2))/nTheta0;

benchmarkCase = struct( ...
    'name', {'circular', 'PT', 'NT'}, ...
    'gfile', { ...
        'geqdsk_circular', ...
        'geqdsk_PT0.6', ...
        'geqdsk_NT0.6'}, ...
    'targetPsiN', {0.8, 0.7, 0.7}, ...
    'shatMaximum', {5.0, 5.0, 7.0}, ...
    'alphaMaximum', {6.0, 6.0, 12.0}, ...
    'nShat', {9, 9, 9}, ...
    'nAlpha', {11, 11, 13}, ...
    'millerFitHalfWidth', {3.e-2, 3.e-2, 8.e-2});

benchmarkResult = repmat(struct(), numel(benchmarkCase), 1);

for caseIndex = 1:numel(benchmarkCase)
    specification = benchmarkCase(caseIndex);
    fprintf('\n============================================================\n');
    fprintf('Standard s-alpha benchmark: %s\n', specification.name);
    fprintf('============================================================\n');

    gfile = fullfile(projectRoot, 'gfiles', specification.gfile);
    referenceEquilibrium = read_geqdsk(gfile);
    referenceFunction = build_interpolants(referenceEquilibrium);

    geqdskDirectState = prepare_salpha_equilibrium( ...
        referenceEquilibrium, referenceFunction, ...
        specification.targetPsiN, ...
        Model="Direct", ...
        NSurfacePoints=nSurfacePoint, ...
        FourierModes=32, ...
        ProjectionIterations=2, ...
        EnforceDirectQ=true, ...
        EnforcePeriodicity=true);

    referenceState = build_reference_state( ...
        specification, referenceEquilibrium, referenceFunction, ...
        geqdskDirectState, nSurfacePoint);

    femEquilibrium = solve_geqdsk_with_fem( ...
        referenceEquilibrium, referenceFunction);

    femDirectState = prepare_fem_salpha_equilibrium( ...
        femEquilibrium, specification.targetPsiN, ...
        AdapterNR=257, ...
        Model="Direct", ...
        NSurfacePoints=nSurfacePoint, ...
        FourierModes=32, ...
        ProjectionIterations=2, ...
        EnforceDirectQ=true, ...
        EnforcePeriodicity=true);

    shatGrid = linspace( ...
        0, specification.shatMaximum, specification.nShat);
    alphaGrid = linspace( ...
        0, specification.alphaMaximum, specification.nAlpha);

    scanOptions = { ...
        'Shat', shatGrid, ...
        'Alpha', alphaGrid, ...
        'Theta0', theta0Grid, ...
        'ThetaBoundary', 5*pi, ...
        'NBalloonPoints', nBalloonPoint, ...
        'EnforcePeriodicity', true, ...
        'Verbose', true};

    fprintf('\nReference scan (%s).\n', referenceState.model);
    referenceScan = scan_salpha_diagram( ...
        referenceState, scanOptions{:});

    fprintf('\nGEQDSK direct-flux-surface scan.\n');
    geqdskDirectScan = scan_salpha_diagram( ...
        geqdskDirectState, scanOptions{:});

    fprintf('\nFEM direct-flux-surface scan.\n');
    femDirectScan = scan_salpha_diagram( ...
        femDirectState, scanOptions{:});

    geqdskComparison = compare_salpha_maps( ...
        geqdskDirectScan, referenceScan);
    femComparison = compare_salpha_maps( ...
        femDirectScan, geqdskDirectScan);

    surfaceComparison = compare_surface_geometry( ...
        femDirectState.localEquilibrium, ...
        geqdskDirectState.localEquilibrium);

    fprintf('\n%s benchmark summary.\n', specification.name);
    print_map_comparison( ...
        'GEQDSK-Direct / reference', geqdskComparison);
    print_map_comparison( ...
        'FEM-Direct / GEQDSK-Direct', femComparison);
    fprintf(['  FEM/GEQDSK direct surface R/Z/Bp/curvature L2 ', ...
        '= %.3e / %.3e / %.3e / %.3e\n'], ...
        surfaceComparison.R, surfaceComparison.Z, ...
        surfaceComparison.Bp, surfaceComparison.curvature);
    fprintf('  FEM GS iterations / residual = %d / %.3e\n', ...
        femEquilibrium.solverResult.iterations, ...
        femEquilibrium.solverResult.finalRelativeResidual);

    assert(referenceScan.numberFailed == 0 && ...
           geqdskDirectScan.numberFailed == 0 && ...
           femDirectScan.numberFailed == 0, ...
        'VERIFY_STANDARD_SALPHA:FailedSolve', ...
        '%s produced failed eigenvalue solves.', specification.name);

    assert(all(referenceScan.lambdaMax(:, 1) < 0) && ...
           all(geqdskDirectScan.lambdaMax(:, 1) < 0) && ...
           all(femDirectScan.lambdaMax(:, 1) < 0), ...
        'VERIFY_STANDARD_SALPHA:ZeroAlpha', ...
        '%s does not remain stable at alpha=0.', specification.name);

    assert(referenceScan.hasMarginalCrossing && ...
           geqdskDirectScan.hasMarginalCrossing && ...
           femDirectScan.hasMarginalCrossing, ...
        'VERIFY_STANDARD_SALPHA:NoMarginalBoundary', ...
        '%s did not capture all three marginal boundaries.', ...
        specification.name);

    assert(geqdskComparison.signAgreement > 0.90 && ...
           geqdskComparison.scaledRmsError < 0.20 && ...
           geqdskComparison.marginalRmsFraction < 0.12, ...
        'VERIFY_STANDARD_SALPHA:DirectReferenceMismatch', ...
        ['%s GEQDSK-Direct stability differs excessively from ', ...
         'the established reference path.'], specification.name);

    assert(femComparison.signAgreement > 0.95 && ...
           femComparison.scaledRmsError < 0.10 && ...
           femComparison.marginalRmsFraction < 0.08, ...
        'VERIFY_STANDARD_SALPHA:FEMMismatch', ...
        ['%s FEM-Direct stability differs excessively from ', ...
         'GEQDSK-Direct.'], specification.name);

    assert(surfaceComparison.Bp < 5.e-2 && ...
           surfaceComparison.curvature < 1.e-1, ...
        'VERIFY_STANDARD_SALPHA:SurfaceGeometry', ...
        '%s FEM and GEQDSK direct geometries differ excessively.', ...
        specification.name);

    figurePath = fullfile( ...
        thisDirectory, sprintf( ...
            'standard_salpha_%s.png', lower(specification.name)));
%     comparisonFigure = plot_three_maps( ...
%         specification, referenceScan, ...
%         geqdskDirectScan, femDirectScan);
%     exportgraphics(comparisonFigure, figurePath, 'Resolution', 160);
%     close(comparisonFigure);

    benchmarkResult(caseIndex).name = specification.name;
    benchmarkResult(caseIndex).specification = specification;
    benchmarkResult(caseIndex).reference = referenceScan;
    benchmarkResult(caseIndex).geqdskDirect = geqdskDirectScan;
    benchmarkResult(caseIndex).femDirect = femDirectScan;
    benchmarkResult(caseIndex).geqdskComparison = geqdskComparison;
    benchmarkResult(caseIndex).femComparison = femComparison;
    benchmarkResult(caseIndex).surfaceComparison = surfaceComparison;
    benchmarkResult(caseIndex).figurePath = figurePath;

    fprintf('  comparison figure             = %s\n', figurePath);
    fprintf('%s benchmark passed.\n', specification.name);
end

resultFile = fullfile(thisDirectory, 'standard_salpha_validation.mat');
save(resultFile, 'benchmarkResult', 'benchmarkCase');

fprintf('\n============================================================\n');
fprintf('Circular, PT, and NT FEM s-alpha validation passed.\n');
fprintf('Saved benchmark data: %s\n', resultFile);
fprintf('============================================================\n');


function state = build_reference_state( ...
    specification, eq, eqfunc, directState, nSurfacePoint)

    if strcmpi(specification.name, 'circular')
        [parameters, boundary] = fit_Circular( ...
            eq, eqfunc, specification.targetPsiN, ...
            NTheta=int32(nSurfacePoint));
        localEquilibrium = Circular_Mercier_Luc( ...
            directState.surface, parameters, boundary);

        state = directState;
        state.model = 'circular-reference';
        state.parameters = parameters;
        state.boundary = boundary;
        state.localEquilibrium = localEquilibrium;
    else
        state = prepare_salpha_equilibrium( ...
            eq, eqfunc, specification.targetPsiN, ...
            Model="Miller", ...
            NSurfacePoints=nSurfacePoint, ...
            RadialFitHalfWidth=specification.millerFitHalfWidth, ...
            NRadialFit=9, ...
            EnforcePeriodicity=true);
        state.model = sprintf('%s-Miller-reference', ...
            specification.name);
    end
end


function equilibrium = solve_geqdsk_with_fem(reference, referenceFunction)
    boundary = clean_boundary(reference.rbbbs, reference.zbbbs);
    referenceSpan = reference.sibry-reference.simag;

    if ~isfinite(referenceSpan) || referenceSpan == 0
        error('VERIFY_STANDARD_SALPHA:FluxSpan', ...
            'The GEQDSK flux span must be finite and nonzero.');
    end

    input = struct();
    input.grid = struct( ...
        'nBoundary', size(boundary, 1), ...
        'NR', 72, ...
        'NZ', 72, ...
        'quadratureDegree', 10, ...
        'nProfile', reference.nw);

    input.dim = struct( ...
        'R0', reference.rcentr, ...
        'B0', reference.fpol(end)/reference.rcentr, ...
        'aMinor', 0.5*range(boundary(:, 1)));

    input.profile = struct( ...
        'mode', 1, ...
        'pprime', reference.pprime(:)*referenceSpan, ...
        'FFprime', reference.ffprim(:)*referenceSpan, ...
        'pedge', reference.pres(end));

    input.boundary = struct( ...
        'R', boundary(:, 1), ...
        'Z', boundary(:, 2), ...
        'psiBoundary', 0);

    input.Picard = struct( ...
        'omega', 0.5, ...
        'maxIterations', 180, ...
        'updateTolerance', 1.e-8, ...
        'residualTolerance', 1.e-8, ...
        'axisMode', 'max', ...
        'symmetryTolerance', 1.e-12, ...
        'fluxSpanTolerance', 1.e-12);

    input.qEvaluation = struct( ...
        'interiorPsiN', unique([ ...
            0.05:0.05:0.80, 0.825:0.025:0.95]).', ...
        'contourNR', 241);

    input.output = struct( ...
        'verbose', false, ...
        'checkTime', false, ...
        'showPlot', false);

    equilibrium = solve_GS(input);

    assert(equilibrium.solverResult.converged, ...
        'VERIFY_STANDARD_SALPHA:GSConvergence', ...
        'The FEM reconstruction of the GEQDSK did not converge.');

    % Confirm that the target surface is inside the range where the saved
    % q profile was directly evaluated, rather than boundary-extrapolated.
    targetValues = [0.7, 0.8];
    for target = targetValues
        if target <= max(input.qEvaluation.interiorPsiN)
            qValue = referenceFunction.q(target);
            assert(isfinite(qValue), ...
                'VERIFY_STANDARD_SALPHA:ReferenceQ', ...
                'The reference q profile is invalid at psiN=%.3f.', ...
                target);
        end
    end
end


function comparison = compare_salpha_maps(actual, reference)
    assert(isequal(actual.shat, reference.shat) && ...
           isequal(actual.alpha, reference.alpha), ...
        'VERIFY_STANDARD_SALPHA:ScanGrid', ...
        'Compared s-alpha maps must use identical grids.');

    actualMap = actual.lambdaMax;
    referenceMap = reference.lambdaMax;
    difference = actualMap-referenceMap;

    referenceScale = max(max(abs(referenceMap), [], 'all'), 1.e-6);
    comparison.rmsError = sqrt(mean(difference.^2, 'all'));
    comparison.scaledRmsError = ...
        comparison.rmsError/referenceScale;
    comparison.maximumError = max(abs(difference), [], 'all');
    comparison.scaledMaximumError = ...
        comparison.maximumError/referenceScale;

    neutralTolerance = 1.e-4*referenceScale;
    classified = abs(referenceMap) > neutralTolerance;
    if any(classified, 'all')
        comparison.signAgreement = mean( ...
            sign(actualMap(classified)) == ...
            sign(referenceMap(classified)));
    else
        comparison.signAgreement = NaN;
    end

    actualMarginal = first_marginal_alpha( ...
        actual.alpha, actualMap);
    referenceMarginal = first_marginal_alpha( ...
        reference.alpha, referenceMap);
    shared = isfinite(actualMarginal) & isfinite(referenceMarginal);

    comparison.actualMarginalAlpha = actualMarginal;
    comparison.referenceMarginalAlpha = referenceMarginal;
    comparison.marginalSharedRows = nnz(shared);

    if any(shared)
        marginalDifference = ...
            actualMarginal(shared)-referenceMarginal(shared);
        alphaSpan = max(reference.alpha)-min(reference.alpha);
        comparison.marginalRmsError = ...
            sqrt(mean(marginalDifference.^2));
        comparison.marginalRmsFraction = ...
            comparison.marginalRmsError/max(alphaSpan, eps);
        comparison.marginalMaximumError = ...
            max(abs(marginalDifference));
    else
        comparison.marginalRmsError = Inf;
        comparison.marginalRmsFraction = Inf;
        comparison.marginalMaximumError = Inf;
    end
end


function marginal = first_marginal_alpha(alpha, lambdaMap)
    marginal = nan(size(lambdaMap, 1), 1);

    for row = 1:size(lambdaMap, 1)
        value = lambdaMap(row, :);
        crossing = find( ...
            value(1:end-1) <= 0 & value(2:end) >= 0, 1, 'first');

        if isempty(crossing)
            continue;
        end

        lambdaLeft = value(crossing);
        lambdaRight = value(crossing+1);
        alphaLeft = alpha(crossing);
        alphaRight = alpha(crossing+1);

        if lambdaRight == lambdaLeft
            marginal(row) = 0.5*(alphaLeft+alphaRight);
        else
            marginal(row) = alphaLeft-lambdaLeft ...
                *(alphaRight-alphaLeft)/(lambdaRight-lambdaLeft);
        end
    end
end


function comparison = compare_surface_geometry(actual, reference)
    comparison = struct();
    comparison.R = relative_l2(actual.R, reference.R);
    comparison.Z = relative_l2(actual.Z, reference.Z);
    comparison.Bp = relative_l2(actual.Bp, reference.Bp);
    comparison.curvature = relative_l2( ...
        actual.invRc, reference.invRc);
end


function print_map_comparison(label, comparison)
    fprintf('  %s\n', label);
    fprintf('    scaled RMS / max map error = %.3e / %.3e\n', ...
        comparison.scaledRmsError, ...
        comparison.scaledMaximumError);
    fprintf('    stability-sign agreement   = %.3f\n', ...
        comparison.signAgreement);
    fprintf(['    marginal RMS/max error     = %.3e / %.3e ', ...
        '(%d shared rows)\n'], ...
        comparison.marginalRmsError, ...
        comparison.marginalMaximumError, ...
        comparison.marginalSharedRows);
end


function figureHandle = plot_three_maps( ...
    specification, reference, geqdskDirect, femDirect)

    maps = { ...
        reference.lambdaMax, ...
        geqdskDirect.lambdaMax, ...
        femDirect.lambdaMax};
    titles = { ...
        sprintf('Reference: %s', reference.model), ...
        'GEQDSK Direct', ...
        'FEM Direct'};

    colorMinimum = min(cellfun( ...
        @(value) min(value, [], 'all'), maps));
    colorMaximum = max(cellfun( ...
        @(value) max(value, [], 'all'), maps));

    figureHandle = figure( ...
        'Color', 'w', ...
        'Visible', 'on', ...
        'Name', sprintf('%s standard s-alpha validation', ...
            specification.name), ...
        'Position', [100, 100, 1480, 440]);
    layout = tiledlayout(figureHandle, 1, 3, ...
        'TileSpacing', 'compact', 'Padding', 'compact');

    for panel = 1:3
        axesHandle = nexttile(layout);
        contourf(axesHandle, ...
            reference.alpha, reference.shat, maps{panel}, ...
            30, 'LineStyle', 'none');
        hold(axesHandle, 'on');
        contour(axesHandle, ...
            reference.alpha, reference.shat, maps{panel}, [0, 0], ...
            'k', 'LineWidth', 2.0);

        if geqdskDirect.equilibriumAlpha >= min(reference.alpha) && ...
                geqdskDirect.equilibriumAlpha <= max(reference.alpha) && ...
                geqdskDirect.equilibriumShat >= min(reference.shat) && ...
                geqdskDirect.equilibriumShat <= max(reference.shat)
            plot(axesHandle, ...
                geqdskDirect.equilibriumAlpha, ...
                geqdskDirect.equilibriumShat, ...
                'p', 'MarkerSize', 11, ...
                'MarkerFaceColor', [1.0, 0.85, 0.1], ...
                'MarkerEdgeColor', 'k');
        end

        clim(axesHandle, [colorMinimum, colorMaximum]);
        grid(axesHandle, 'on');
        box(axesHandle, 'on');
        xlabel(axesHandle, '$\alpha$', 'Interpreter', 'latex');
        ylabel(axesHandle, '$\hat{s}$', 'Interpreter', 'latex');
        title(axesHandle, titles{panel}, 'Interpreter', 'none');
    end

    colormap(figureHandle, turbo);
    colorbarHandle = colorbar;
    colorbarHandle.Layout.Tile = 'east';
    title(layout, sprintf( ...
        '%s, $\\psi_N=%.2f$: largest ballooning eigenvalue', ...
        specification.name, specification.targetPsiN), ...
        'Interpreter', 'latex');
end


function boundary = clean_boundary(R, Z)
    boundary = [R(:), Z(:)];
    scale = max([range(boundary(:, 1)), range(boundary(:, 2)), 1]);
    tolerance = 1.e-12*scale;

    keep = [true; hypot(diff(boundary(:, 1)), ...
        diff(boundary(:, 2))) > tolerance];
    boundary = boundary(keep, :);

    if norm(boundary(end, :)-boundary(1, :)) <= tolerance
        boundary(end, :) = [];
    end

    if size(boundary, 1) < 3 || any(~isfinite(boundary), 'all')
        error('VERIFY_STANDARD_SALPHA:Boundary', ...
            'The GEQDSK boundary is invalid.');
    end
end


function error = relative_l2(actual, reference)
    error = norm(actual(:)-reference(:)) ...
        /max(norm(reference(:)), eps);
end

%% verify_fem_direct_ballooning_point.m
% Validate the shape-independent flux-surface local-equilibrium path.
% GEQDSK and FEM equilibria are reduced to the same direct Mercier-Luc
% interface without a Miller fit, then passed through the unchanged
% ballooning coefficient and eigenvalue solver.

%% Reuse the verified reference/FEM equilibrium construction
verify_ballooning_adapter;

addpath( ...
    fullfile(projectRoot, 'local_equilibrium'), ...
    fullfile(projectRoot, 'ballooning_equation'), ...
    fullfile(projectRoot, 'sturm_liouville_solver'), ...
    fullfile(projectRoot, 'salpha'));

%% Direct flux-surface local equilibria
nLocalPoint = 512;
fourierModes = 32;

referenceState = prepare_salpha_equilibrium( ...
    reference, referenceFunction, targetPsiN, ...
    Model="Direct", ...
    NSurfacePoints=nLocalPoint, ...
    FourierModes=fourierModes, ...
    ProjectionIterations=2, ...
    EnforceDirectQ=true, ...
    EnforcePeriodicity=true);

femState = prepare_fem_salpha_equilibrium( ...
    equilibrium, targetPsiN, ...
    AdapterNR=257, ...
    Model="Direct", ...
    NSurfacePoints=nLocalPoint, ...
    FourierModes=fourierModes, ...
    ProjectionIterations=2, ...
    EnforceDirectQ=true, ...
    EnforcePeriodicity=true);

%% One unchanged ballooning solve
theta0 = 0;
thetaBoundary = 5*pi;
thetaGrid = linspace(-thetaBoundary, thetaBoundary, 151).';

referencePoint = solve_direct_ballooning_point( ...
    referenceState, theta0, thetaBoundary, thetaGrid);

femPoint = solve_direct_ballooning_point( ...
    femState, theta0, thetaBoundary, thetaGrid);

%% Geometry and coefficient comparisons
referenceGeometry = referenceState.localEquilibrium;
femGeometry = femState.localEquilibrium;

RRelativeL2 = relative_l2( ...
    femGeometry.R, referenceGeometry.R);
ZRelativeL2 = relative_l2( ...
    femGeometry.Z, referenceGeometry.Z);
BpRelativeL2 = relative_l2( ...
    femGeometry.Bp, referenceGeometry.Bp);
curvatureRelativeL2 = relative_l2( ...
    femGeometry.invRc, referenceGeometry.invRc);

normalDifference = hypot( ...
    femGeometry.sinu-referenceGeometry.sinu, ...
    femGeometry.cosu-referenceGeometry.cosu);
normalRmsDifference = sqrt(mean(normalDifference.^2));

shatRelativeError = abs(femState.shat-referenceState.shat) ...
    /max(abs(referenceState.shat), 1.e-8);
alphaRelativeError = abs(femState.alpha-referenceState.alpha) ...
    /max(abs(referenceState.alpha), 1.e-8);

gRelativeL2 = relative_l2(femPoint.g, referencePoint.g);
cRelativeL2 = relative_l2(femPoint.c, referencePoint.c);
fRelativeL2 = relative_l2(femPoint.f, referencePoint.f);

lambdaDifference = abs( ...
    femPoint.lambda-referencePoint.lambda);
lambdaScaledDifference = lambdaDifference ...
    /max(abs(referencePoint.lambda), 1);

referenceDirectDiagnostic = ...
    referenceState.diagnostics.directGeometry;
femDirectDiagnostic = ...
    femState.diagnostics.directGeometry;

fprintf('\nDirect flux-surface FEM/GEQDSK diagnostics.\n');
fprintf('  target psiN                       = %.4f\n', ...
    targetPsiN);
fprintf('  reference/FEM shat                = %+.8e / %+.8e\n', ...
    referenceState.shat, femState.shat);
fprintf('  reference/FEM alpha               = %+.8e / %+.8e\n', ...
    referenceState.alpha, femState.alpha);
fprintf('  shat / alpha relative difference  = %.3e / %.3e\n', ...
    shatRelativeError, alphaRelativeError);
fprintf('  R / Z relative L2                 = %.3e / %.3e\n', ...
    RRelativeL2, ZRelativeL2);
fprintf('  Bp / curvature relative L2        = %.3e / %.3e\n', ...
    BpRelativeL2, curvatureRelativeL2);
fprintf('  normal RMS vector difference      = %.3e\n', ...
    normalRmsDifference);
fprintf('  g / c / f relative L2             = %.3e / %.3e / %.3e\n', ...
    gRelativeL2, cRelativeL2, fRelativeL2);
fprintf('  reference/FEM largest lambda      = %+.8e / %+.8e\n', ...
    referencePoint.lambda, femPoint.lambda);
fprintf('  scaled lambda difference          = %.3e\n', ...
    lambdaScaledDifference);
fprintf('  reference/FEM surface psiN RMS    = %.3e / %.3e\n', ...
    referenceDirectDiagnostic.psiNRms, ...
    femDirectDiagnostic.psiNRms);
fprintf('  reference/FEM q correction        = %.8f / %.8f\n', ...
    referenceDirectDiagnostic.qCorrection, ...
    femDirectDiagnostic.qCorrection);
fprintf('  reference/FEM PEST closure        = %.3e / %.3e\n', ...
    referenceDirectDiagnostic.PESTClosure, ...
    femDirectDiagnostic.PESTClosure);
fprintf('  FEM theta_psi periodic closure    = %.3e\n', ...
    femState.thetaDiag.closure_used);

%% Acceptance checks
assert(femDirectDiagnostic.psiNRms < 2.e-3 && ...
       femDirectDiagnostic.psiNMaximum < 1.e-2, ...
    'VERIFY_DIRECT_POINT:SurfaceFlux', ...
    'The direct FEM geometry drifted away from the target flux surface.');

assert(abs(femDirectDiagnostic.qRelativeError) < 1.e-10 && ...
       abs(femDirectDiagnostic.PESTClosure) < 1.e-10, ...
    'VERIFY_DIRECT_POINT:SurfaceClosure', ...
    'The direct FEM geometry does not reproduce q or PEST closure.');

assert(BpRelativeL2 < 5.e-2 && ...
       curvatureRelativeL2 < 1.e-1 && ...
       normalRmsDifference < 5.e-2, ...
    'VERIFY_DIRECT_POINT:Geometry', ...
    'The direct FEM and GEQDSK surface geometries differ excessively.');

assert(gRelativeL2 < 1.e-1 && ...
       cRelativeL2 < 1.e-1 && ...
       fRelativeL2 < 1.e-1, ...
    'VERIFY_DIRECT_POINT:Coefficients', ...
    'The direct FEM and GEQDSK ballooning coefficients differ excessively.');

assert(lambdaScaledDifference < 1.e-1 && ...
       sign(femPoint.lambda) == sign(referencePoint.lambda), ...
    'VERIFY_DIRECT_POINT:Eigenvalue', ...
    'The direct FEM and GEQDSK stability results are inconsistent.');

assert(abs(femState.thetaDiag.closure_used) < 1.e-10, ...
    'VERIFY_DIRECT_POINT:Periodicity', ...
    'The direct FEM theta_psi did not close periodically.');

fprintf('\nP3 FEM direct-flux-surface ballooning verification passed.\n');


function point = solve_direct_ballooning_point( ...
    state, theta0, thetaBoundary, thetaGrid)

    coefficient = evaluate_gcf( ...
        state.thetaDiag, theta0, ...
        theta_bnd=thetaBoundary, ...
        a_N=state.normalization.aN, ...
        B_N=state.normalization.BN);

    g = interp1( ...
        coefficient.theta, coefficient.g, thetaGrid, 'pchip');
    c = interp1( ...
        coefficient.theta, coefficient.c, thetaGrid, 'pchip');
    f = interp1( ...
        coefficient.theta, coefficient.f, thetaGrid, 'pchip');

    [Gmatrix, Cmatrix, Fmatrix, thetaDof] = ...
        construct_matrix(thetaGrid, g, c, f);

    lambda = calculate_eigenvalue( ...
        thetaDof, Gmatrix, Cmatrix, Fmatrix, 'dirichlet');

    point = struct();
    point.coefficient = coefficient;
    point.theta = thetaGrid;
    point.g = g;
    point.c = c;
    point.f = f;
    point.lambda = lambda(1);
end


function error = relative_l2(actual, reference)
    error = norm(actual(:)-reference(:)) ...
        /max(norm(reference(:)), eps);
end

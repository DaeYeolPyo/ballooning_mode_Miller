%% verify_fem_ballooning_point.m
% Compare one complete local-equilibrium ballooning solve through
%   1) the original GEQDSK path and
%   2) the P3 FEM adapter path.
%
% The shared downstream routines evaluate_theta_psi, evaluate_gcf,
% construct_matrix, and calculate_eigenvalue are not modified.

%% Reuse the verified reference/FEM equilibrium construction
verify_ballooning_adapter;

addpath( ...
    fullfile(projectRoot, 'local_equilibrium'), ...
    fullfile(projectRoot, 'ballooning_equation'), ...
    fullfile(projectRoot, 'sturm_liouville_solver'), ...
    fullfile(projectRoot, 'salpha'));

%% Prepare the same local-equilibrium state through both input routes
nLocalPoint = 512;
radialFitHalfWidth = 3.e-2;
nRadialFit = 9;

referenceState = prepare_salpha_equilibrium( ...
    reference, referenceFunction, targetPsiN, ...
    Model="Miller", ...
    NSurfacePoints=nLocalPoint, ...
    RadialFitHalfWidth=radialFitHalfWidth, ...
    NRadialFit=nRadialFit, ...
    EnforcePeriodicity=true);

femState = prepare_fem_salpha_equilibrium( ...
    equilibrium, targetPsiN, ...
    AdapterNR=257, ...
    Model="Miller", ...
    NSurfacePoints=nLocalPoint, ...
    RadialFitHalfWidth=radialFitHalfWidth, ...
    NRadialFit=nRadialFit, ...
    EnforcePeriodicity=true);

%% Evaluate g,c,f and solve one unchanged Sturm-Liouville problem
theta0 = 0;
thetaBoundary = 5*pi;
nBalloonPoint = 151;
thetaGrid = linspace( ...
    -thetaBoundary, thetaBoundary, nBalloonPoint).';

referencePoint = solve_ballooning_point( ...
    referenceState, theta0, thetaBoundary, thetaGrid);

femPoint = solve_ballooning_point( ...
    femState, theta0, thetaBoundary, thetaGrid);

%% Comparison diagnostics
shapeNames = {'R0', 'r', 'delta', 'kappa', ...
    'dR0_dr', 's_delta', 's_kappa'};

shapeRelativeError = zeros(numel(shapeNames), 1);
for k = 1:numel(shapeNames)
    name = shapeNames{k};
    referenceValue = referenceState.parameters.(name);
    femValue = femState.parameters.(name);
    shapeRelativeError(k) = abs(femValue-referenceValue) ...
        /max(abs(referenceValue), 1.e-8);
end

shatRelativeError = abs(femState.shat-referenceState.shat) ...
    /max(abs(referenceState.shat), 1.e-8);

alphaRelativeError = abs(femState.alpha-referenceState.alpha) ...
    /max(abs(referenceState.alpha), 1.e-8);

gRelativeL2 = relative_l2(femPoint.g, referencePoint.g);
cRelativeL2 = relative_l2(femPoint.c, referencePoint.c);
fRelativeL2 = relative_l2(femPoint.f, referencePoint.f);

lambdaDifference = abs( ...
    femPoint.lambda-referencePoint.lambda);
lambdaScaledDifference = lambdaDifference ...
    /max(abs(referencePoint.lambda), 1);

FFprimePeriodicRelativeDifference = abs( ...
    femState.thetaDiag.FFprime_periodic ...
    - referenceState.thetaDiag.FFprime_periodic) ...
    /max(abs(referenceState.thetaDiag.FFprime_periodic), 1);

fprintf('\nFEM/GEQDSK local ballooning-point diagnostics.\n');
fprintf('  target psiN                       = %.4f\n', ...
    targetPsiN);
fprintf('  reference/FEM shat                = %+.8e / %+.8e\n', ...
    referenceState.shat, femState.shat);
fprintf('  reference/FEM alpha               = %+.8e / %+.8e\n', ...
    referenceState.alpha, femState.alpha);
fprintf('  shat / alpha relative difference  = %.3e / %.3e\n', ...
    shatRelativeError, alphaRelativeError);
fprintf('  max Miller-parameter relative     = %.3e\n', ...
    max(shapeRelativeError));
fprintf('  g / c / f relative L2             = %.3e / %.3e / %.3e\n', ...
    gRelativeL2, cRelativeL2, fRelativeL2);
fprintf('  reference/FEM largest lambda      = %+.8e / %+.8e\n', ...
    referencePoint.lambda, femPoint.lambda);
fprintf('  scaled lambda difference          = %.3e\n', ...
    lambdaScaledDifference);
fprintf('  periodic FFprime relative         = %.3e\n', ...
    FFprimePeriodicRelativeDifference);
fprintf('  FEM periodic closure              = %.3e\n', ...
    femState.thetaDiag.closure_used);

%% Acceptance checks for this coupling stage
assert(max(shapeRelativeError) < 2.e-2, ...
    'VERIFY_BALLOONING_POINT:MillerParameters', ...
    'The FEM and GEQDSK Miller fits differ excessively.');

assert(shatRelativeError < 2.e-2 && alphaRelativeError < 2.e-2, ...
    'VERIFY_BALLOONING_POINT:SAlphaCoordinates', ...
    'The FEM and GEQDSK equilibrium s-alpha coordinates differ excessively.');

assert(gRelativeL2 < 5.e-2 && ...
       cRelativeL2 < 5.e-2 && ...
       fRelativeL2 < 5.e-2, ...
    'VERIFY_BALLOONING_POINT:Coefficients', ...
    'The FEM and GEQDSK ballooning coefficients differ excessively.');

assert(lambdaScaledDifference < 5.e-2, ...
    'VERIFY_BALLOONING_POINT:Eigenvalue', ...
    'The FEM and GEQDSK ballooning eigenvalues differ excessively.');

assert(abs(femState.thetaDiag.closure_used) < 1.e-10, ...
    'VERIFY_BALLOONING_POINT:Periodicity', ...
    'The FEM local-equilibrium theta_psi did not close periodically.');

fprintf('\nP3 FEM single-point ballooning verification passed.\n');


function point = solve_ballooning_point( ...
    state, theta0, thetaBoundary, thetaGrid)

    coefficient = evaluate_gcf( ...
        state.thetaDiag, theta0, ...
        theta_bnd=thetaBoundary, ...
        a_N=state.normalization.aN, ...
        B_N=state.normalization.BN);

    g = interp1( ...
        coefficient.theta, coefficient.g, thetaGrid, 'pchip');
    c = interp1( ...
        coefficient.theta, coefficient.c, thetaGrid, 'pchip');
    f = interp1( ...
        coefficient.theta, coefficient.f, thetaGrid, 'pchip');

    [Gmatrix, Cmatrix, Fmatrix, thetaDof] = ...
        construct_matrix(thetaGrid, g, c, f);

    lambda = calculate_eigenvalue( ...
        thetaDof, Gmatrix, Cmatrix, Fmatrix, 'dirichlet');

    point = struct();
    point.coefficient = coefficient;
    point.theta = thetaGrid;
    point.g = g;
    point.c = c;
    point.f = f;
    point.lambda = lambda(1);
end


function error = relative_l2(actual, reference)
    error = norm(actual(:)-reference(:)) ...
        /max(norm(reference(:)), eps);
end

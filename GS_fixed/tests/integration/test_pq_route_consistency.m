%% Local utility functions

function value = relative_l2_error(candidate, reference)
%RELATIVE_L2_ERROR Relative Euclidean error.

    candidate = candidate(:);
    reference = reference(:);

    if numel(candidate) ~= numel(reference)
        error('TEST_PQ_ROUTE:ComparisonSize', ...
            'The compared vectors must have equal lengths.');
    end

    numerator = norm(candidate-reference);
    denominator = max(norm(reference), eps);

    value = numerator/denominator;
end


function value = relative_scalar_error(candidate, reference)
%RELATIVE_SCALAR_ERROR Relative scalar error.

    validateattributes(candidate, {'numeric'}, ...
        {'real', 'finite', 'scalar'});

    validateattributes(reference, {'numeric'}, ...
        {'real', 'finite', 'scalar'});

    value = ...
        abs(candidate-reference)/max(abs(reference), eps);
end

function [xi_q, w_q] = GauLeg_points(nq)
    % The abscissa and weights are hard-coded for now,
    % but it should be updated to explicit formula

    switch nq
        case 1
            xi_q = 0;
            w_q = 2;
        case 2
            xi_q = [-1/sqrt(3), 1/sqrt(3)];
            w_q = [1, 1];
        case 3
            xi_q = [-sqrt(3/5), 0, sqrt(3/5)];
            w_q = [5/9, 8/9, 5/9];
        case 4
            xi_q = [-sqrt(3/7 + (2/7)*sqrt(6/5)), ...
                -sqrt(3/7 - (2/7)*sqrt(6/5)), ...
                sqrt(3/7 - (2/7)*sqrt(6/5)), ...
                sqrt(3/7 + (2/7)*sqrt(6/5))];
            w_q = [(18 - sqrt(30))/36, (18 + sqrt(30))/36, ...
                (18 + sqrt(30))/36, (18 - sqrt(30))/36];
        case 5
            xi_q = [-sqrt(5 + 2*sqrt(10/7))/3, ...
                -sqrt(5 - 2*sqrt(10/7))/3, ...
                0, ...
                sqrt(5 - 2*sqrt(10/7))/3, ...
                sqrt(5 + 2*sqrt(10/7))/3];
            w_q = [(322 - 13*sqrt(70))/900, ...
                (322 + 13*sqrt(70))/900, ...
                128/225, ...
                (322 + 13*sqrt(70))/900, ...
                (322 - 13*sqrt(70))/900];
        otherwise
            error("The GauLeg_points are implemented up to nq=5")
    end
end
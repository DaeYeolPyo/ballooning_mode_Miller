function projectRoot = setup_indented_cshape_scan()
%SETUP_INDENTED_CSHAPE_SCAN Add the existing GS and ballooning dependencies.
    here = fileparts(mfilename('fullpath'));
    projectRoot = fileparts(here);
    addpath(here, fullfile(projectRoot,'GS_fixed'), ...
        fullfile(projectRoot,'equilibrium'), ...
        fullfile(projectRoot,'local_equilibrium'), ...
        fullfile(projectRoot,'salpha'), ...
        fullfile(projectRoot,'sturm_liouville_solver'));
    setup_solve_GS;
end

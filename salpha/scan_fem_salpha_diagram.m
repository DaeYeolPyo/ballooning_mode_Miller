function [result, state] = scan_fem_salpha_diagram( ...
    equilibrium, targetPsiN, opts)
%SCAN_FEM_SALPHA_DIAGRAM Run a direct s-alpha scan from a P3 FEM result.
%
%   [result,state] = SCAN_FEM_SALPHA_DIAGRAM(equilibrium,targetPsiN)
%
% This convenience entry point performs only FEM equilibrium
% postprocessing before calling the unchanged ballooning solver chain.

    arguments
        equilibrium (1,1) struct
        targetPsiN (1,1) double

        opts.AdapterNR (1,1) double = 257
        opts.AdapterNZ (1,1) double = NaN
        opts.NSurfacePoints (1,1) double = 512
        opts.FourierModes (1,1) double = 32
        opts.ProjectionIterations (1,1) double = 2
        opts.EnforceDirectQ (1,1) logical = true

        opts.Shat double = linspace(0, 5, 31)
        opts.Alpha double = linspace(0, 6, 31)
        opts.Theta0 double = []
        opts.ThetaBoundary (1,1) double = 5*pi
        opts.NBalloonPoints (1,1) double = 151
        opts.EnforcePeriodicity (1,1) logical = true
        opts.Verbose (1,1) logical = true
    end

    state = prepare_fem_salpha_equilibrium( ...
        equilibrium, targetPsiN, ...
        AdapterNR=opts.AdapterNR, ...
        AdapterNZ=opts.AdapterNZ, ...
        Model="Direct", ...
        NSurfacePoints=opts.NSurfacePoints, ...
        FourierModes=opts.FourierModes, ...
        ProjectionIterations=opts.ProjectionIterations, ...
        EnforceDirectQ=opts.EnforceDirectQ, ...
        EnforcePeriodicity=opts.EnforcePeriodicity);

    result = scan_salpha_diagram( ...
        state, ...
        Shat=opts.Shat, ...
        Alpha=opts.Alpha, ...
        Theta0=opts.Theta0, ...
        ThetaBoundary=opts.ThetaBoundary, ...
        NBalloonPoints=opts.NBalloonPoints, ...
        EnforcePeriodicity=opts.EnforcePeriodicity, ...
        Verbose=opts.Verbose);

    result.adapterDiagnostics = state.adapterDiagnostics;
end

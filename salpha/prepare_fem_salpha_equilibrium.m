function state = prepare_fem_salpha_equilibrium( ...
    equilibrium, targetPsiN, opts)
%PREPARE_FEM_SALPHA_EQUILIBRIUM Adapt a P3 GS result for an s-alpha scan.
%
%   state = PREPARE_FEM_SALPHA_EQUILIBRIUM( ...
%       equilibrium, targetPsiN)
%
% This is the FEM-facing entry point for the existing local-equilibrium
% ballooning solver.  It changes only equilibrium preprocessing; the
% downstream coefficient, matrix, and eigenvalue routines are unchanged.

    arguments
        equilibrium (1,1) struct
        targetPsiN (1,1) double
        opts.AdapterNR (1,1) double = 257
        opts.AdapterNZ (1,1) double = NaN
        opts.Model (1,1) string = "Miller"
        opts.NSurfacePoints (1,1) double = 1024
        opts.RadialFitHalfWidth (1,1) double = 3.e-2
        opts.NRadialFit (1,1) double = 9
        opts.EnforcePeriodicity (1,1) logical = true
        opts.FourierModes (1,1) double = 32
        opts.ProjectionIterations (1,1) double = 2
        opts.EnforceDirectQ (1,1) logical = true
    end

    [eq, eqfunc, adapterDiagnostics] = ...
        build_ballooning_adapter( ...
            equilibrium, ...
            NR=opts.AdapterNR, ...
            NZ=opts.AdapterNZ);

    state = prepare_salpha_equilibrium( ...
        eq, eqfunc, targetPsiN, ...
        Model=opts.Model, ...
        NSurfacePoints=opts.NSurfacePoints, ...
        RadialFitHalfWidth=opts.RadialFitHalfWidth, ...
        NRadialFit=opts.NRadialFit, ...
        EnforcePeriodicity=opts.EnforcePeriodicity, ...
        FourierModes=opts.FourierModes, ...
        ProjectionIterations=opts.ProjectionIterations, ...
        EnforceDirectQ=opts.EnforceDirectQ);

    state.eq = eq;
    state.eqfunc = eqfunc;
    state.adapterDiagnostics = adapterDiagnostics;
end
